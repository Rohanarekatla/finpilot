"""Tune the forecaster's spread inflation on the dev seeds (never on the test seeds).

For each candidate factor it runs the same rolling-origin backtest as `eval.run_eval`
(history up to month k, forecast to the end of month k+1) and reports, for regular
months only, how often the actual month-end balance fell inside the P10-P90 band and
the median forecast's error. The smallest factor reaching 80% coverage goes into
`app/agents/forecaster.py::SPREAD_INFLATION`; `eval.run_eval` then reports it on test seeds.

    python -m eval.tune_forecast
"""
from __future__ import annotations

import os
import sys
from pathlib import Path

import numpy as np
import pandas as pd

os.environ.setdefault("FINPILOT_OFFLINE", "1")
ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from app.agents import analyzer, categorizer, forecaster  # noqa: E402
from app.llm import MeshLLM  # noqa: E402
from app.synthetic import PERSONAS, generate  # noqa: E402
from app.taxonomy import merchant_key  # noqa: E402

DEV_SEEDS = list(range(100, 115))
FACTORS = [1.0, 1.1, 1.2, 1.3, 1.4, 1.5, 1.75, 2.0]
TARGET_COVERAGE = 80.0  # the nominal coverage of a P10-P90 band


def folds() -> list[tuple[pd.DataFrame, analyzer.Analysis, float, int, float]]:
    """(history, analysis, start balance, horizon, actual month-end balance) for each regular month."""
    llm = MeshLLM(api_key="", offline=True)
    out = []
    for persona in PERSONAS:
        for seed in DEV_SEEDS:
            s = generate(persona, seed)
            df = s.transactions.drop(columns=["true_category"]).copy()
            df["merchant"] = df["description"].map(merchant_key)
            c = categorizer.categorize(df, mode="heuristic", llm=llm)
            months = sorted(c["date"].dt.to_period("M").unique())
            for cut in months[3:-2]:  # the last month holds the planted anomalies
                hist = c[c["date"].dt.to_period("M") <= cut]
                nxt = c[c["date"].dt.to_period("M") == cut + 1]
                a = analyzer.analyze(hist, narrate=False)
                horizon = ((cut + 1).end_time.normalize() - a.as_of.normalize()).days
                out.append((hist, a, float(hist["balance"].iloc[-1]), horizon, float(nxt["balance"].iloc[-1]), seed))
    return out


def main() -> None:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")  # ₹ on a Windows console
    data = folds()
    print("# Forecast spread tuning (dev seeds only)\n")
    print(f"Generated by `python -m eval.tune_forecast`: {len(data)} regular-month folds on dev seeds "
          f"{DEV_SEEDS[0]}-{DEV_SEEDS[-1]}.\n")
    print("| Spread factor | P10-P90 coverage | Month-end balance MAPE | Mean band width |")
    print("|---|---|---|---|")
    chosen = None
    for k in FACTORS:
        cov, err, width = [], [], []
        for hist, a, bal, horizon, actual, seed in data:
            fc = forecaster.forecast(hist, a, bal, horizon_days=horizon, n_sims=300, seed=seed, spread=k)
            lo, mid, hi = np.percentile(fc.paths[:, -1], [10, 50, 90])
            cov.append(lo <= actual <= hi)
            err.append(abs(mid - actual) / abs(actual))
            width.append(hi - lo)
        c = float(np.mean(cov)) * 100
        print(f"| {k} | {c:.1f}% | {np.mean(err) * 100:.2f}% | ₹{np.mean(width):,.0f} |")
        if chosen is None and c >= TARGET_COVERAGE:
            chosen = (k, c)
    if chosen:
        print(f"\nChosen: factor **{chosen[0]}**, the smallest that reaches the nominal {TARGET_COVERAGE:.0f}% "
              f"coverage ({chosen[1]:.1f}%). Under-covering is the worse error for a money forecast: it makes a "
              "risky month look safe.")


if __name__ == "__main__":
    main()
